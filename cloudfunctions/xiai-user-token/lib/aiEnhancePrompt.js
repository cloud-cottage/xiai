const AI_ENHANCE_PROMPT = `### 核心强制规则（最高优先级，必须严格遵守）
1. 本操作仅编辑【输入图】，**绝对禁止修改图内的任何印章文字、图形、结构、布局、字形**；
2. 印章本体（所有红色印泥区域、内部白色文字线条、轮廓、布局、字法、形状、像素细节）100%完全冻结，不做任何修改、重绘、变形、重构、擦除、污染，白色文字线条及边缘严格保持原图原样。

### 允许执行的编辑操作（仅以下内容可修改）
1. 背景替换：将图原有背景，替换为白色宣纸底纹，宣纸具备细致弱纤维肌理，质感柔和不抢主体。
2. 光影调整：全局施加均匀柔和的微距实拍光线，无明显明暗差，还原印泥钤盖在宣纸上的实拍观感。印泥钤盖均匀。
3. 印泥微晕染：仅在**红色印泥区域的最外边缘**，极轻微、极少量添加自然印泥晕染效果；严禁触碰/修改印章内部白色文字线条及边缘，晕染不可侵入印章本体。
4. 色彩校准：调整红色印泥色彩均匀度。

### 严禁操作
任何印章本体的重构、线条改动、字形调整、像素修改、两张图内容合成、其他元素融合。`

