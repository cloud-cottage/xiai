/**
 * t2s 逐字表 ＝ s2t 逐字表的**取反**（繁体 → 简体）。
 *
 * 为什么不另存一份 `TSCharacters` 全表：① **单一真源** —— s2t 表本来就取自 `STCharacters`
 * 里「在 `TSCharacters` 方向不变」的条目，逐条取反就是**同口径**的 t2s 表，可复算、可对拍；
 * ② 省一份 ~34 KB 的原始表进主包（只有用到才建，且建表成本极低）。
 * 表里没有的字**原样保留**。
 *
 * ## 反查 tie-break 规则（多值不再「首个胜出」）
 *
 * 全表体检（3,757 对）实测：逐字表**源字严格按码位升序**（0 处逆序）⇒ 旧口径「首个胜出」
 * 实际等价于「**最低码位胜出**」，而**码位序不表达常用性**：
 *   · CJK 扩展 A（U+3400–U+4DBF）整体**低于**基本区（U+4E00–U+9FFF）⇒ 扩展 A 的罕见变体
 *     抢走基本区的常用简体形（实测 2 例：`钁`→`䦆`(U+4986) 而非 `镢`、`靦`→`䩄`(U+4A44) 而非 `腼`）；
 *   · CJK 扩展 B 及以后（U+20000+）整体**高于**基本区 ⇒ 当一个繁体字**只有**扩展区候选时
 *     （其常用简体形不在表内 —— 如 `闲` 属上下文相关字而未进表），反查会输出生僻的扩展区字面：
 *     实测 1,129 个反查键命中，含 **`閒`→`𫔮`(U+2B52E)**（⇒ `toSimplifiedText('閒章')='𫔮章'`）。
 *
 * 故按**候选字自身的 Unicode 码位区段**分档，**建表门 ＝ 最优档必须等于档 0**：
 *   档 0 ＝ CJK 统一表意文字·基本区（U+4E00–U+9FFF）＝ 常用简体字形 ⇒ **唯一可建键的档**；
 *   档 1 ＝ CJK 扩展 A / 兼容区等其它统一表意文字（罕用）⇒ **不再作兜底**（K-t2s2 收口）；
 *   档 2 ＝ **禁用档**：CJK 扩展 B 及以后（U+20000+）与 PUA（U+E000–U+F8FF / U+F0000+）。
 * 候选里**一个档 0 都没有**（该繁体字没有任何基本区简体形）⇒ **不建键** —— 反查面上**原样保留**，
 * 与「表未覆盖即原样保留」「宁可少转一个字，也不猜」同口径（`闲`/`閑` 与本单收掉的 135 键行为一致）。
 * **为什么档 1 也一并踢掉**：档 1 的输出是多数字体**缺字形**的扩展 A 字形 ⇒ 用户看到豆腐块，
 * 比「没转」更差（实测 135 个档 1 键里 81 键的键自身就是常用繁体字 ⇒ 真会被打到）。
 * **禁用档门同样下沉到词组路径**（见 `gateForbiddenChars()`）：词组替换值里落禁用档的字
 * **保留原形**（如 `二噁英` 不再变成 `二𫫇英`）。
 * 规则只依据 Unicode 标准的码位区段（`t2sReverseTier()`），**不含任何字表 / 白名单 / 特例**；
 * 逐字表内容、两张词组表**内容**与 **s2t 方向逐字未变** —— 只改了**反查索引的建法**与
 * **t2s 词组值的过门**（s2t 方向不经过该门）。
 */
let T2S_GLYPH_MAP = null

/**
 * 反查候选的**档位**（0 ＝ 常用·基本区；1 ＝ 罕用·扩展 A 等，可兜底；2 ＝ 禁用 · 扩展 B+ 与 PUA）。
 * 纯代码点判定，自测 / 质检可独立复算。
 */
export function t2sReverseTier(ch) {
  const c = typeof ch === 'string' ? ch.codePointAt(0) : NaN
  if (!Number.isFinite(c)) return 2
  if (c >= 0x4e00 && c <= 0x9fff) return 0 // CJK 统一表意文字·基本区
  if ((c >= 0xe000 && c <= 0xf8ff) || c >= 0xf0000) return 2 // PUA / PUA 补充面
  if (c >= 0x20000) return 2 // CJK 扩展 B 及以后
  return 1 // CJK 扩展 A / 兼容区 / 其它
}

/** 档 0 值（常用简体字形所在区段；＝**唯一可建反查键的档**）。 */
export const T2S_COMMON_TIER = 0

/** 禁用档档位值（扩展 B+ 与 PUA 的字面**永不**作为输出字形：逐字层与词组层同门）。 */
export const T2S_FORBIDDEN_TIER = 2

function t2sGlyphMap() {
  if (T2S_GLYPH_MAP) return T2S_GLYPH_MAP
  const map = new Map()
  s2tGlyphMap().forEach((to, from) => {
    // 建表门：**最优档 ≠ 档 0 ⇒ 不建键**（档 1 的罕用扩展 A 字形不再作兜底，档 2 本就不许出现）。
    if (t2sReverseTier(from) !== T2S_COMMON_TIER) return
    if (!map.has(to)) map.set(to, from) // 同档（皆档 0）保持先到者 ＝ 原口径，收敛面最小
  })
  T2S_GLYPH_MAP = map
  return map
}

/** t2s 逐字表的条目数（自测 / 质检；与 s2t 表逐条互逆）。 */
export function t2sGlyphTableInfo() {
  return { size: t2sGlyphMap().size }
}

/** t2s 逐字表的可读导出（自测 / 质检：全表可枚举、可复算）。 */
export function t2sGlyphTable() {
  const out = {}
  t2sGlyphMap().forEach((to, from) => {
    out[from] = to
  })
  return out
}

