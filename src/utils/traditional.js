/** 上下文相关字集合（懒建；滤掉排版空白，按码位切分）。 */
let S2T_CONTEXT_SET = null
function s2tContextSet() {
  if (S2T_CONTEXT_SET) return S2T_CONTEXT_SET
  S2T_CONTEXT_SET = new Set(Array.from(S2T_CONTEXT_SENSITIVE_CHARS).filter(isGlyphChar))
  return S2T_CONTEXT_SET
}

/** 文本中出现的上下文相关字（去重、保序）。 */
export function contextSensitiveCharsIn(text) {
  const set = s2tContextSet()
  const out = []
  for (const ch of text) {
    if (set.has(ch) && !out.includes(ch)) out.push(ch)
  }
  return out
}

/** 逐字表（懒建；`Map` 键为单字）。 */
let S2T_GLYPH_MAP = null

/**
 * 逐字表的**排版空白**（两个字符串都是「每 96 字换行 + 两格缩进」⇒ 结构逐位相同，
 * 过滤掉换行与缩进后仍然逐位对应）。
 */
function isGlyphChar(ch) {
  return ch !== '\n' && ch !== ' ' && ch !== '\r'
}

/**
 * 建表：**按码位**（`Array.from` 按 Unicode 码位切分 —— 表里有 CJK 扩展区的代理对字符，
 * 用 `str[i]` 按 UTF-16 码元索引会从第一个代理对起**整体错位**，实测踩过）。
 */
function s2tGlyphMap() {
  if (S2T_GLYPH_MAP) return S2T_GLYPH_MAP
  const source = Array.from(S2T_GLYPH_SOURCE).filter(isGlyphChar)
  const target = Array.from(S2T_GLYPH_TARGET).filter(isGlyphChar)
  const size = Math.min(source.length, target.length)
  const map = new Map()
  for (let i = 0; i < size; i += 1) map.set(source[i], target[i])
  map.aligned = source.length === target.length
  S2T_GLYPH_MAP = map
  return map
}

/** 逐字表的条目数与对齐状态（自测 / 质检；错位即判失败）。 */
export function s2tGlyphTableInfo() {
  const map = s2tGlyphMap()
  return { size: map.size, aligned: map.aligned === true }
}

/**
 * **繁化一段文本（R-57 的逐字口径，`db.js` 迁移用的是本函数）**：逐字查表，表里没有的字
 * （含全部「上下文相关字」，见 `S2T_CONTEXT_SENSITIVE_CHARS`）**原样保留** —— 不猜、不丢、
 * 不发明规则。因此「整串 `s2t`」与「逐字转换」在词组层可能不同（`干净` ⇒ `干淨` vs `乾淨`）：
 * 逐字表对这些字**直接不转**，并由迁移报告逐条登记（`report.context_sensitive`）。
 * 需要词组层就形的场合用 `toTraditionalFull()`（异步、词组表按需加载）。
 * @param {string} text 任意文本（空串 / 非字符串 ⇒ 空串）
 * @returns {string} 繁化后的文本
 */
export function toTraditionalText(text) {
  if (typeof text !== 'string' || text === '') return ''
  const map = s2tGlyphMap()
  let out = ''
  for (const ch of text) out += map.get(ch) || ch
  return out
}

/** 逐字表的可读导出（自测 / 质检：全表可枚举、可复算）。 */
export function s2tGlyphTable() {
  const out = {}
  s2tGlyphMap().forEach((to, from) => {
    out[from] = to
  })
  return out
}
