/**
 * 玺爱 · 简繁转换（**单一真源**：逐字表 / 词组表 / 四个契约只此一份）
 *
 * ## 对外契约（R-8 trad 单冻结；另一单按此编码 —— **同步·异步、名字与语义不得改**）
 *   ① `toTraditionalText(text)` —— **同步**：只用 s2t **逐字表**（上下文相关字**原样保留**）。
 *   ② `toSimplifiedText(text)` —— **同步**：t2s **逐字层**。
 *   ③ `toTraditionalFull(text)` —— **异步**：先 s2t **词组表**、后 s2t 逐字表
 *      （词组表用 `import()` **按需加载** ⇒ 两张词组表都不进主包）。
 *   ④ `toSimplifiedFull(text)` —— **异步**：先 t2s 词组表、后 t2s 逐字表（同 ③ 按需加载）。
 *      t2s 输出面另有**禁用档门**（逐字键与词组值一律只出基本区字形，详见 ② 的档位说明与
 *      `gateForbiddenChars()`）—— 这一门**只作用于 t2s 方向**，③ 不受影响。
 * 共同口径：**幂等**（已是目标形态 ⇒ 原样返回）、**不抛错**、空串 / 非字符串入参 ⇒ 空串。
 * 为此 ③④ 在词组表**加载失败**（离线 / 分块缺失）时**回落**同步逐字层：仍不抛错、仍幂等，
 * 且逐字表**只会**给出正确的繁体字形、**不会**写错字（宁可少转一个字，也不猜 —— 与
 * 迁移报告的 `context_sensitive` 同一口径）。
 *
 * ## 数据来源（OpenCC；dev 期用临时 venv 生成，运行期**零依赖**）
 *   · 逐字表 `S2T_GLYPH_SOURCE` / `S2T_GLYPH_TARGET`（各 3,878 字）—— 本文件内，随主包；
 *   · 词组表 `./traditional-phrases-s2t.js`（`STPhrases` 49,051 条）/
 *     `./traditional-phrases-t2s.js`（`TSPhrases` 277 条）—— **独立模块**，由 ③④ 懒加载。
 * 算法口径＝OpenCC **`s2t` / `t2s`**（**禁 `s2tw` / `s2twp`**：台湾用词与字形不在本单范围）。
 * 产品与 npm **都不依赖** Python / opencc：它们只在生成期出现，仓库里只有静态表。
 *
 * ## 层级说明（本单按指令破例之处，已在规范缺口登记）
 * 数据层（`src/data/db.js`）此前**不** import `utils/**`（见 `assetmeta.js` 文件头）。
 * 本单把「上屏文案繁化」这块**工具**下沉到本文件作单一真源（表**只此一份**、禁复制），
 * 故 `db.js` 改为 import + re-export 转发 —— 迁移逻辑本身**逐字未变**（它只用同步的
 * `toTraditionalText`），行为由 fixture 对照逐行证明。
 *
 * ## 一条如实登记的差异
 * `toTraditionalText` 的入参归一：旧实现是 `String(text)` 兜底（`toTraditionalText(123)`
 * ⇒ `'123'`）。本单按 ③ 的冻结契约把**四个导出**统一成「非字符串 ⇒ 空串」。迁移侧三个
 * 调用点在调用前都已经 `String(...)` / `typeof === 'string'` 守卫 ⇒ **传进来的永远是字符串**，
 * 迁移行为不受影响（fixture 改前/改后逐行相同）。
 */

