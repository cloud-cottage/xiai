/* ============================================================================
 * ③ 词组表索引（**按需加载**：只有 ③④ 全量转换才会 `import()` 到，主包不含两张表）
 * ========================================================================== */

/** s2t 词组表索引（懒建；`null` ＝ 表尚未加载）。 */
let S2T_PHRASE_INDEX = null
/** t2s 词组表索引（懒建）。 */
let T2S_PHRASE_INDEX = null
/** 词组表**加载状态**（自测 / 质检：证明「按需加载」真的发生了）。 */
const PHRASE_LOADED = { s2t: false, t2s: false }

/**
 * 建索引：`首字 → { lengths: 键长降序去重, entries: 键→值 }`。
 * 为什么按首字分组：绝大多数位置首字就不在表里 ⇒ 一次 `Map.get` 就短路，
 * 不必对每个位置都试 2..16 的窗口（那是 15 次切片 + 哈希）。
 * 表格式见词组表模块文件头：一条一行、`键\t值`（≥ 2 字，恒等条目也保留）。
 */
function buildPhraseIndex(raw) {
  const groups = new Map()
  let entries = 0
  let maxKeyLength = 0
  for (const line of String(raw || '').split('\n')) {
    if (!line) continue
    const tab = line.indexOf('\t')
    if (tab <= 0) continue
    const key = line.slice(0, tab)
    const value = line.slice(tab + 1)
    const chars = Array.from(key)
    const head = chars[0]
    let group = groups.get(head)
    if (!group) {
      group = { lengths: new Set(), entries: new Map() }
      groups.set(head, group)
    }
    group.entries.set(key, value)
    group.lengths.add(chars.length)
    if (chars.length > maxKeyLength) maxKeyLength = chars.length
    entries += 1
  }
  groups.forEach((group) => {
    group.lengths = [...group.lengths].sort((a, b) => b - a) // 键长降序 ⇒ 最长匹配优先
  })
  return { groups, entries, maxKeyLength }
}

/** 在 `chars[i]` 处做**最长匹配**（键长降序、命中即止）；未命中 ⇒ `null`。 */
function matchPhrase(index, chars, i) {
  const group = index.groups.get(chars[i])
  if (!group) return null
  const rest = chars.length - i
  for (const len of group.lengths) {
    if (len > rest) continue
    const key = len === 1 ? chars[i] : chars.slice(i, i + len).join('')
    const value = group.entries.get(key)
    if (value !== undefined) return { value, length: len }
  }
  return null
}

/**
 * **禁用档门（只作用于 t2s 词组路径）**：词组命中的替换值**逐字过门** —— 值里落在禁用档
 * （扩展 B+ / PUA）的字**保留原形**（＝源文本同一位置的字），禁用档字形**永不**上屏。
 *
 * 为什么不直接在词组表里删条目：两张词组表内容**冻结**（OpenCC 原样、禁手改，恒等条目还起
 * 「阻挡最长匹配」的作用）；为什么保留原形而不是回落到逐字表：与建表门**同一口径** ——
 * 「宁可少转一个字，也不猜」，输出面只允许基本区字形。（例：`二噁英` 保持 `二噁英`。）
 * 值按**码位**与命中的源片段同位置对齐（两张词组表均为「与键等长」）；
 * 若某位置没有原位可退（表被改动导致值长于键 —— 冻结表现实测不出现），该字**直接丢弃**，
 * 以保证「禁用档字形永不输出」这一不变式在任何表数据下都成立。
 * @param {string} value 词组表给出的替换值
 * @param {string[]} chars 源文本的码位数组
 * @param {number} start 本次命中的起始下标
 * @returns {string} 过门后的替换值
 */
function gateForbiddenChars(value, chars, start) {
  let out = ''
  const vch = Array.from(value)
  for (let k = 0; k < vch.length; k += 1) {
    if (t2sReverseTier(vch[k]) !== T2S_FORBIDDEN_TIER) {
      out += vch[k]
      continue
    }
    const orig = chars[start + k]
    out += orig !== undefined ? orig : ''
  }
  return out
}

/**
 * 全量转换：逐位置「先词组表、后单字表」。
 * 词组命中 ⇒ 整段替换并跳过其长度（`phraseGuard` 存在时先过门，**只有 t2s 方向**用它）；
 * 否则取单字表（表外字含上下文相关字 ⇒ 原样保留）。
 * 按**码位**推进（`Array.from`）：表里有 CJK 扩展区的代理对字符，按 UTF-16 码元会错位。
 */
function convertWithPhrases(source, index, charMap, phraseGuard) {
  const chars = Array.from(source)
  let out = ''
  let i = 0
  while (i < chars.length) {
    const hit = matchPhrase(index, chars, i)
    if (hit) {
      out += phraseGuard ? phraseGuard(hit.value, chars, i) : hit.value
      i += hit.length
      continue
    }
    out += charMap.get(chars[i]) || chars[i]
    i += 1
  }
  return out
}

/** 词组表加载状态（自测 / 质检：证明「按需加载」——全量转换前 `false`、后 `true`）。 */
export function phraseTableLoaded() {
  return { s2t: PHRASE_LOADED.s2t, t2s: PHRASE_LOADED.t2s }
}

/**
 * **繁化（全量）**：先 s2t 词组表、后 s2t 逐字表。**异步** —— 词组表 `import()` 按需加载。
 * 词组表命中 ⇒ 连上下文相关字一起定形（`干净` ⇒ `乾淨`）；未命中 ⇒ 逐字表口径
 * （上下文相关字原样保留）。幂等：已是繁体 ⇒ 原样返回。
 * @param {string} text 任意文本（空串 / 非字符串 ⇒ 空串）
 * @returns {Promise<string>} 繁化后的文本（**不抛错**：词组表拉不到 ⇒ 回落同步逐字层）
 */
export async function toTraditionalFull(text) {
  if (typeof text !== 'string' || text === '') return ''
  let index = S2T_PHRASE_INDEX
  if (!index) {
    try {
      const mod = await import('./traditional-phrases-s2t.js')
      index = buildPhraseIndex(mod.S2T_PHRASE_TABLE)
      S2T_PHRASE_INDEX = index
      PHRASE_LOADED.s2t = true
    } catch {
      return toTraditionalText(text)
    }
  }
  return convertWithPhrases(text, index, s2tGlyphMap())
}

/**
 * **简化（全量）**：先 t2s 词组表、后 t2s 逐字表。**异步**（词组表按需加载）。
 * 词组值经**禁用档门**（`gateForbiddenChars()`）：值里落扩展 B+ / PUA 的字**保留原形**
 * （`二噁英` 保持 `二噁英`），与逐字层「档 0 才建键」同一安全口径 —— 禁用档字形不上屏。
 * 幂等：已是简体 ⇒ 原样返回。
 * @param {string} text 任意文本（空串 / 非字符串 ⇒ 空串）
 * @returns {Promise<string>} 简化后的文本（**不抛错**：词组表拉不到 ⇒ 回落同步逐字层）
 */
export async function toSimplifiedFull(text) {
  if (typeof text !== 'string' || text === '') return ''
  let index = T2S_PHRASE_INDEX
  if (!index) {
    try {
      const mod = await import('./traditional-phrases-t2s.js')
      index = buildPhraseIndex(mod.T2S_PHRASE_TABLE)
      T2S_PHRASE_INDEX = index
      PHRASE_LOADED.t2s = true
    } catch {
      return toSimplifiedText(text)
    }
  }
  return convertWithPhrases(text, index, t2sGlyphMap(), gateForbiddenChars)
}
